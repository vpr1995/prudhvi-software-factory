import { gateEntries } from './gate-list.mjs';

const EDIT_MATCHER = 'Edit|Write|MultiEdit|NotebookEdit';
const HOOK_FOLDER = '.claude/hooks';
const ALLOW = [
  'Bash(node common/scripts/install-run-rush.js:*)',
  'Bash(node scripts/gates/anti-skip.mjs:*)',
  'Bash(node scripts/gates/bruno-coverage.mjs:*)',
  'Bash(node scripts/gates/playwright-coverage.mjs:*)',
  'Bash(bash .claude/hooks/stop-gate.sh --write-state-only)',
  'Bash(git status:*)',
  'Bash(git diff:*)',
  'Bash(git log:*)',
  'Bash(git show:*)',
  'Bash(gh pr view:*)',
];
const READ_DENY = ['Read(**/.env)', 'Read(**/.env.*)', 'Read(~/.aws/**)', 'Read(~/.ssh/**)'];

/**
 * Makes the permission rule for a gate glob. Claude Code matches path rules for file changes only
 * through `Edit(...)`, and it applies them to Write, MultiEdit and NotebookEdit too.
 *
 * @param {string} glob - A gate glob from gate-files.json.
 * @returns {string} A deny rule.
 */
export function denyRuleFor(glob) {
  return glob.includes('/') && !glob.startsWith('**/')
    ? `Edit(/${glob})`
    : `Edit(**/${glob.replace(/^\*\*\//, '')})`;
}

/**
 * Makes one hook entry.
 *
 * @param {string} script - Hook script name without `.sh`.
 * @param {number} timeout - Time limit in seconds.
 * @param {string} [flags] - Extra arguments.
 * @returns {{ type: 'command', command: string, timeout: number }} The entry.
 */
function hook(script, timeout, flags = '') {
  const command = `bash "$CLAUDE_PROJECT_DIR"/${HOOK_FOLDER}/${script}.sh${flags === '' ? '' : ` ${flags}`}`;
  return { type: 'command', command, timeout };
}

/**
 * Builds the settings for the Claude hooks and permissions.
 *
 * @returns {Record<string, unknown>} The settings object. A human copies it to `.claude/settings.json`.
 */
export function buildSettings() {
  const deny = [
    ...new Set([...gateEntries().map((entry) => denyRuleFor(entry.glob)), ...READ_DENY]),
  ];
  return {
    $comment:
      'Generated by scripts/gates/build-settings.mjs from scripts/gates/gate-files.json. Do not edit by hand. A human copies this file to .claude/settings.json (a gate file) after review.',
    permissions: { allow: ALLOW, deny },
    hooks: {
      SessionStart: [{ hooks: [hook('session-start', 30)] }],
      UserPromptSubmit: [{ hooks: [hook('prompt-context', 30)] }],
      PreToolUse: [
        { matcher: EDIT_MATCHER, hooks: [hook('protect-gates', 30), hook('block-secrets', 60)] },
        { matcher: 'Bash', hooks: [hook('guard-bash', 30), hook('require-verify', 60)] },
      ],
      PostToolUse: [
        { matcher: EDIT_MATCHER, hooks: [hook('post-edit', 180), hook('typecheck-project', 240)] },
        { matcher: 'Bash', hooks: [hook('post-bash', 30)] },
      ],
      PostToolUseFailure: [{ matcher: 'Bash', hooks: [hook('post-bash', 30)] }],
      Stop: [{ hooks: [hook('stop-gate', 3600)] }],
      SubagentStop: [{ hooks: [hook('stop-gate', 600, '--fast')] }],
    },
  };
}

/**
 * Formats the settings as the file text.
 *
 * @returns {string} JSON with a final newline.
 */
export function settingsText() {
  return `${JSON.stringify(buildSettings(), null, 2)}\n`;
}
